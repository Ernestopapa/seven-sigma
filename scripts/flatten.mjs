// Flatten contracts/SevenSigma.sol (with OpenZeppelin deps) into one file
// for manual BscScan verification via the web UI.
// Usage: node scripts/flatten.mjs
// Writes verification/SevenSigma.flattened.sol
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const seen = new Set();
const out = [];

function resolveImport(importPath, fromFile) {
  if (importPath.startsWith("@")) {
    return path.join(root, "node_modules", importPath);
  }
  return path.resolve(path.dirname(fromFile), importPath);
}

function flattenFile(full) {
  const key = path.resolve(full);
  if (seen.has(key)) return;
  seen.add(key);
  let content = fs.readFileSync(full, "utf8");
  const lines = content.split("\n");
  for (const line of lines) {
    const m = line.match(/^\s*import\s+(?:[^'"]+\s+from\s+)?["']([^"']+)["'];/);
    if (m) {
      flattenFile(resolveImport(m[1], full));
    }
  }
  // Strip SPDX + pragma lines (kept once at the top) and import lines
  const body = lines
    .filter((l) => !l.match(/^\s*import\s+/) && !l.match(/SPDX-License-Identifier/) && !l.match(/^\s*pragma solidity/))
    .join("\n");
  out.push(`// ---- ${path.relative(root, full)} ----\n${body}`);
}

flattenFile(path.join(root, "contracts", "SevenSigma.sol"));

fs.mkdirSync(path.join(root, "verification"), { recursive: true });
const flat = `// SPDX-License-Identifier: MIT\npragma solidity ^0.8.26;\n\n// Flattened SevenSigma (SIGMA) — generated by scripts/flatten.mjs\n// for manual BscScan verification. Original sources in contracts/ +\n// @openzeppelin/contracts v5.6.1. Compiler: solc 0.8.26, Cancun,\n// optimizer enabled, runs 200.\n\n${out.join("\n")}\n`;
fs.writeFileSync(path.join(root, "verification", "SevenSigma.flattened.sol"), flat);
console.log("wrote verification/SevenSigma.flattened.sol,", flat.length, "chars");
